// Real brand logos → the episode's extras/logos.js (PV.LOGOS). Never draw brand logos by hand.
// Usage (from an episode dir): node ../../kit/tools/logos.mjs anthropic claude openai langchain ...
//   name      → simple-icons first (single-colour official mark), then iconify "logos" "<name>-icon" (mark only), then "<name>" (may be a wordmark)
//   si:name / logos:name → force a source
// Re-running replaces the file with exactly the names given, so list every logo the episode uses.
import fs from 'fs';
import path from 'path';
import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const si = require('simple-icons');
const LG = require('@iconify-json/logos/icons.json');

const siKey = (n) => 'si' + n.replace(/[^a-z0-9]/gi, '').toLowerCase().replace(/^./, (c) => c.toUpperCase());
function fromSi(n) {
  const i = si[siKey(n)];
  return i && { title: i.title, source: 'simple-icons', hex: '#' + i.hex, svg: `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path fill="#${i.hex}" d="${i.path}"/></svg>` };
}
function fromLogos(n) {
  const i = LG.icons[n];
  if (!i) return null;
  const w = i.width ?? LG.width ?? 256, h = i.height ?? LG.height ?? 256;
  return { title: n, source: 'iconify-logos', svg: `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}">${i.body}</svg>` };
}
const out = {}, missing = [];
for (const arg of process.argv.slice(2)) {
  const [src, n] = arg.includes(':') ? arg.split(':') : [null, arg];
  const hit = src === 'si' ? fromSi(n) : src === 'logos' ? fromLogos(n) : fromSi(n) || fromLogos(n + '-icon') || fromLogos(n);
  if (hit) out[n] = hit; else missing.push(arg);
}
if (missing.length) {
  console.error(`找不到这些 logo：${missing.join(' ')}\n可以去查：simple-icons 的 slug（https://simpleicons.org），或 iconify logos 集（https://icon-sets.iconify.design/logos/）`);
  process.exit(1);
}
const file = path.join(process.cwd(), 'extras/logos.js');
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(file, `/* Generated by kit/tools/logos.mjs — real brand logos (simple-icons / iconify logos). Do not edit. */\nPV.LOGOS = ${JSON.stringify(out)};\n`);
for (const [n, v] of Object.entries(out)) console.log(`✓ ${n.padEnd(16)} ${v.source}`);
console.log(`→ extras/logos.js（记得在 script.js 的 META.extras 里登记 'extras/logos.js'）`);
